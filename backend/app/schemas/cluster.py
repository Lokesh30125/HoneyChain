def to_cluster_public(cluster, member_count: int = 0, batch_count: int = 0) -> ClusterWithCounts:
    """Cluster plus its member and batch counts.

    Both counts are passed in from single aggregate queries rather than read from
    ``cluster.beekeepers`` / ``cluster.batches``, which would trigger one SELECT
    per row when listing clusters.
    """
    return ClusterWithCounts(
        id=cluster.id,
        cluster_code=cluster.cluster_code,
        cluster_name=cluster.cluster_name,
        district=cluster.district,
        state=cluster.state,
        description=cluster.description,
        coordinator_name=cluster.coordinator_name,
        coordinator_phone=cluster.coordinator_phone,
        is_active=cluster.is_active,
        created_at=cluster.created_at,
        updated_at=cluster.updated_at,
        member_count=member_count,
        batch_count=batch_count,
    )


