class ClusterWithCounts(ClusterPublic):
    """Cluster plus its member and batch counts (database aggregates, not estimates)."""

    member_count: int = 0
    #: Honey batches currently placed in this cluster, counted from
    #: ``honey_batches.cluster_id``. It is the same number the cluster's own batch
    #: table has rows, so the register can never promise more than it shows.
    batch_count: int = 0


class ClusterDependencies(BaseModel):
    """What is recorded under a cluster, each figure counted from its own table.

    Read before a deletion, and shown on the cluster's page, because the two
    questions are the same question: *is anything here?* A cluster with records
    under it is history — honey that was harvested, packed and shipped — and
    history is not deleted to tidy a register.
    """

    beekeepers: int = 0
    hives: int = 0
    collections: int = 0
    batches: int = 0
    laboratory_tests: int = 0
    packaging_runs: int = 0
    packages: int = 0
    #: Shipments raised off this cluster's batches — the last stage of the chain,
    #: counted through the packages that came off its honey.
    shipments: int = 0

    @property
    def total(self) -> int:
        return (
            self.beekeepers
            + self.hives
            + self.collections
            + self.batches
            + self.laboratory_tests
            + self.packaging_runs
            + self.packages
            + self.shipments
        )

    def as_counts(self) -> dict[str, int]:
        """The counts as a screen reads them, named as a person would name them."""
        return {
            "Beekeepers": self.beekeepers,
            "Hives": self.hives,
            "Collections": self.collections,
            "Batches": self.batches,
            "Laboratory tests": self.laboratory_tests,
            "Packaging runs": self.packaging_runs,
            "Packages": self.packages,
            "Shipments": self.shipments,
        }


class ClusterDetail(BaseModel):
    cluster: ClusterPublic
    member_count: int = 0
    members: list[dict] = Field(default_factory=list)
    #: Everything recorded under this cluster. Dynamic, counted from the tables.
    dependencies: ClusterDependencies = Field(default_factory=ClusterDependencies)
    #: Whether the cluster may be removed at all, and why not when it may not.
    can_delete: bool = False
    delete_blocked_reason: str | None = None


class ClusterDeleteRequest(BaseModel):
    """``DELETE /api/v1/clusters/{id}``."""

    model_config = ConfigDict(extra="forbid")

    reason: str | None = Field(
        default=None,
        max_length=300,
        description="Why the cluster is being removed. Recorded in the audit log.",
    )
    confirm: bool = Field(
        default=False,
        description=(
            "Must be true. Removing a cluster is deliberate, and a stray request must not do it."
        ),
    )


