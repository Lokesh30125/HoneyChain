class ClusterStageBreakdown(BaseModel):
    """How much of the cluster's honey has reached each stage.

    Cumulative by nature — honey cannot be delivered without having been
    collected — and read from the batches' own stage records, never from a
    per-cluster status somebody maintains.
    """

    collection: int = 0
    processing: int = 0
    laboratory: int = 0
    packaging: int = 0
    distribution: int = 0
    delivered: int = 0


class ClusterBatchAnalytics(BaseModel):
    """The cluster's production figures, every one of them a count of real rows."""

    cluster_id: uuid.UUID
    totals: ClusterBatchTotals
    status_breakdown: ClusterStageBreakdown
    by_status: dict[str, int] = Field(default_factory=dict)
    processing: dict[str, int] = Field(default_factory=dict)
